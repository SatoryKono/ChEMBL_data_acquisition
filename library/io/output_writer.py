"""High-level helpers to persist standard pipeline artefacts deterministically."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from ..common.csv_utils import write_csv_deterministic

OUTPUT_DIR = Path("data/output")

__all__ = ["StandardOutputArtifacts", "save_standard_outputs", "OUTPUT_DIR"]


@dataclass(frozen=True, slots=True)
class StandardOutputArtifacts:
    """Paths of the primary dataset and accompanying QA reports."""

    dataset: Path
    correlation_report: Path
    quality_report: Path


def _ensure_output_directory(path: Path) -> None:
    """Create ``path`` when missing."""

    if path.exists():
        if not path.is_dir():  # pragma: no cover - defensive guard
            raise NotADirectoryError(f"{path} is not a directory")
        return
    path.mkdir(parents=True, exist_ok=True)


def _remove_sidecars(path: Path) -> None:
    """Remove deterministic writer sidecar files for ``path`` when present."""

    meta = path.with_suffix(path.suffix + ".meta.yaml")
    lock = Path(f"{meta}.lock")
    meta.unlink(missing_ok=True)
    lock.unlink(missing_ok=True)


def save_standard_outputs(
    df_main: pd.DataFrame,
    df_corr: pd.DataFrame,
    df_qc: pd.DataFrame,
    table_name: str,
    date_tag: str,
    *,
    key_columns: Sequence[str] | None = None,
    column_order: Sequence[str] | None = None,
    output_dir: Path | str | None = None,
    output_path: Path | str | None = None,
    cleanup_source: bool = True,
) -> StandardOutputArtifacts:
    """Persist the canonical dataset together with QC artefacts.

    Parameters
    ----------
    df_main:
        Aggregated dataset for the table.
    df_corr:
        Correlation metrics generated for ``df_main``.
    df_qc:
        Quality-control summary for ``df_main``.
    table_name:
        Logical name of the table (``document``, ``target`` and so on).
    date_tag:
        UTC date token formatted as ``YYYYMMDD``.
    key_columns:
        Optional sequence of columns used to deterministically order
        ``df_main`` before writing.
    column_order:
        Optional preferred column ordering for ``df_main``.
    output_dir:
        Directory for writing the artefacts. When omitted, :data:`OUTPUT_DIR`
        (``data/output``) is used. The parameter is ignored when
        ``output_path`` is supplied; in that case the parent directory of
        ``output_path`` becomes the target location.
    output_path:
        Optional original dataset path. When provided, the dataset is written
        back to this location and the accompanying reports reuse the same
        stem. When omitted the artefacts default to the canonical
        ``output.<table>_<date>`` naming scheme. If the resulting dataset path
        differs from ``output_path`` the original file (and its optional
        ``.meta.yaml`` sidecar) is deleted when ``cleanup_source`` evaluates
        to ``True``.
    cleanup_source:
        Remove ``output_path`` when it does not match the canonical dataset
        path. Defaults to ``True`` so that legacy exports do not leave stray
        files behind.

    Notes
    -----
    Metadata sidecars generated by the deterministic CSV writer are removed so
    that only the three canonical CSV artefacts remain in ``destination_dir``
    by default.

    Returns
    -------
    StandardOutputArtifacts
        Paths to the dataset, correlation report and quality report.
    """

    resolved_output_dir = Path(output_dir) if output_dir is not None else OUTPUT_DIR

    dataset_path: Path
    destination_dir: Path
    dataset_stem: str
    if output_path is not None:
        dataset_path = Path(output_path)
        destination_dir = dataset_path.parent
        dataset_stem = dataset_path.stem
    else:
        destination_dir = resolved_output_dir
        dataset_stem = f"output.{table_name}_{date_tag}"
        dataset_path = destination_dir / f"{dataset_stem}.csv"

    _ensure_output_directory(destination_dir)

    correlation_path = destination_dir / (
        f"{dataset_stem}_data_correlation_report_table.csv"
    )
    quality_path = destination_dir / f"{dataset_stem}_quality_report_table.csv"

    key_cols = list(key_columns or [])
    if not key_cols and not df_main.empty:
        key_cols = [str(df_main.columns[0])]

    effective_column_order = (
        list(column_order) if column_order is not None else list(df_main.columns)
    )
    write_csv_deterministic(
        df_main,
        dataset_path,
        key_cols=key_cols,
        col_order=effective_column_order,
    )
    _remove_sidecars(dataset_path)

    qc_key_cols: list[str] = []
    if not df_qc.empty:
        qc_key_cols = [str(df_qc.columns[0])]
    write_csv_deterministic(df_qc, quality_path, key_cols=qc_key_cols)
    _remove_sidecars(quality_path)

    corr_key_cols: list[str] = []
    if not df_corr.empty:
        corr_key_cols = [str(df_corr.columns[0])]
    write_csv_deterministic(df_corr, correlation_path, key_cols=corr_key_cols)
    _remove_sidecars(correlation_path)

    artifacts = StandardOutputArtifacts(
        dataset=dataset_path,
        correlation_report=correlation_path,
        quality_report=quality_path,
    )

    if cleanup_source and output_path is not None and Path(output_path) != dataset_path:
        Path(output_path).unlink(missing_ok=True)
        Path(f"{output_path}.meta.yaml").unlink(missing_ok=True)

    return artifacts
